// iOS / Android (Capacitor): アプリに入れたスクリプト類が、ビルドの後に書き換えられていないかを
// 起動時に確かめるネイティブコードを、Capacitor のプロジェクトへ入れる。
//
// Android: 別の鍵で署名し直した APK を配れるので、スクリプト類の SHA-256 をアプリのコード (dex) に持たせ、
//          起動時 (ContentProvider) に assets と照合する。合わなければ起動しない。
// iOS:     アプリ全体が署名で封印されていて、書き換えたものは通常の端末では起動しない。ここで足すのは、
//          署名の検証が働かない端末でスクリプトだけ差し替えられるのを止めるための照合。一覧は
//          バンドルの中 (public/) に置くので、署名し直せる相手には効かない。
import fs from "node:fs";
import path from "node:path";
import { hashData, isCodeFile } from "./integrity.js";

const walk = (directory: string): string[] =>
    fs.readdirSync(directory, { "withFileTypes": true })
        .flatMap((entry) => entry.isDirectory()
            ? walk(path.join(directory, entry.name))
            : entry.isFile() ? [path.join(directory, entry.name)] : []);

/** 一覧のファイル名 (public/ の直下に置く。iOS だけが使う)。 */
export const IOS_MANIFEST_NAME = "next2d-integrity.txt";

/**
 * 同期済みの資材ディレクトリから、照合の一覧の行を作る。1 行 1 ファイルで "<SHA-256><空白 2 つ><キー>"。
 * キーは base からの相対パス (区切りは "/")。対象は public/ 以下のスクリプト類と、extra に挙げた設定ファイル。
 */
export const createNativeIntegrityLines = (base: string, extra: string[] = []): string[] => {
    const publicDir = path.join(base, "public");
    const files = fs.existsSync(publicDir) ? walk(publicDir) : [];
    const keys = files
        .map((file) => path.relative(base, file).split(path.sep).join("/"))
        .filter((key) => isCodeFile(key))
        .concat(extra.filter((name) => fs.existsSync(path.join(base, name))));
    return keys.map((key) => {
        if (/[\r\n]/.test(key)) {
            throw new Error(`A file name with a line break cannot be listed for the integrity check: ${JSON.stringify(key)}`);
        }
        return `${hashData(fs.readFileSync(path.join(base, key)))}  ${key}`;
    }).sort();
};

const BEGIN = "next2d-integrity:begin";
const END = "next2d-integrity:end";

// ---------------------------------------------------------------------------------------------
// Android
// ---------------------------------------------------------------------------------------------

const ANDROID_PACKAGE = "app.next2d.integrity";

/** 照合の処理。内容はビルドによらず同じなので、ゲームのリポジトリに入れておける。 */
export const ANDROID_CHECK_SOURCE = `package ${ANDROID_PACKAGE};

import android.content.ContentProvider;
import android.content.ContentValues;
import android.content.res.AssetManager;
import android.database.Cursor;
import android.net.Uri;

import java.io.IOException;
import java.io.InputStream;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HashMap;
import java.util.Locale;
import java.util.Map;

/**
 * Generated by @next2d/builder. Do not edit.
 *
 * Checks, before anything else in the app runs, that the game's script files in the APK are the ones
 * that were built. The expected SHA-256 hashes are compiled into Next2DAssetIntegrityManifest
 * (generated on every build). A changed or added script stops the app from starting.
 */
public final class Next2DAssetIntegrity extends ContentProvider {

    private static final String[] CODE_EXTENSIONS = { ".js", ".mjs", ".html", ".json", ".wasm" };

    @Override
    public boolean onCreate() {
        final String[] lines = manifestLines();
        if (lines.length == 0 || getContext() == null) {
            return true;
        }
        try {
            verify(getContext().getAssets(), lines);
        } catch (IOException | NoSuchAlgorithmException error) {
            throw new IllegalStateException("The game files could not be verified.", error);
        }
        return true;
    }

    /** The manifest class is generated by the builder; without it (a build that skipped the builder) nothing is checked. */
    private static String[] manifestLines() {
        try {
            final Object lines = Class.forName("${ANDROID_PACKAGE}.Next2DAssetIntegrityManifest").getField("LINES").get(null);
            return lines instanceof String[] ? (String[]) lines : new String[0];
        } catch (ReflectiveOperationException error) {
            return new String[0];
        }
    }

    private static void verify(AssetManager assets, String[] lines) throws IOException, NoSuchAlgorithmException {
        final Map<String, String> expected = new HashMap<>();
        for (String line : lines) {
            // "<64 hex digits><two spaces><path relative to assets/>"
            expected.put(line.substring(66), line.substring(0, 64));
        }
        for (Map.Entry<String, String> entry : expected.entrySet()) {
            if (!entry.getValue().equals(hash(assets, entry.getKey()))) {
                throw new IllegalStateException("The game files have been modified: " + entry.getKey());
            }
        }
        rejectUnlistedScripts(assets, "public", expected);
    }

    /** A script that was added after the build is not in the list. */
    private static void rejectUnlistedScripts(AssetManager assets, String directory, Map<String, String> expected) throws IOException {
        final String[] names = assets.list(directory);
        if (names == null) {
            return;
        }
        for (String name : names) {
            final String path = directory + "/" + name;
            final String[] children = assets.list(path);
            if (children != null && children.length > 0) {
                rejectUnlistedScripts(assets, path, expected);
            } else if (isCode(name) && !expected.containsKey(path)) {
                throw new IllegalStateException("The game files have been modified: " + path);
            }
        }
    }

    private static boolean isCode(String name) {
        final String lower = name.toLowerCase(Locale.ROOT);
        for (String extension : CODE_EXTENSIONS) {
            if (lower.endsWith(extension)) {
                return true;
            }
        }
        return false;
    }

    private static String hash(AssetManager assets, String path) throws IOException, NoSuchAlgorithmException {
        final MessageDigest digest = MessageDigest.getInstance("SHA-256");
        try (InputStream input = assets.open(path)) {
            final byte[] buffer = new byte[65536];
            int read;
            while ((read = input.read(buffer)) > 0) {
                digest.update(buffer, 0, read);
            }
        }
        final StringBuilder hex = new StringBuilder(64);
        for (byte value : digest.digest()) {
            hex.append(Character.forDigit((value >> 4) & 0xF, 16)).append(Character.forDigit(value & 0xF, 16));
        }
        return hex.toString();
    }

    @Override
    public Cursor query(Uri uri, String[] projection, String selection, String[] selectionArgs, String sortOrder) {
        return null;
    }

    @Override
    public String getType(Uri uri) {
        return null;
    }

    @Override
    public Uri insert(Uri uri, ContentValues values) {
        return null;
    }

    @Override
    public int delete(Uri uri, String selection, String[] selectionArgs) {
        return 0;
    }

    @Override
    public int update(Uri uri, ContentValues values, String selection, String[] selectionArgs) {
        return 0;
    }
}
`;

const javaString = (value: string): string =>
    `"${value.replace(/\\/g, "\\\\").replace(/"/g, "\\\"")}"`;

/** ビルドごとに変わる一覧。ゲームのリポジトリには入れない (同じ場所の .gitignore で外す)。 */
export const renderAndroidManifestSource = (lines: string[]): string => [
    `package ${ANDROID_PACKAGE};`,
    "",
    "/** Generated by @next2d/builder on every build. SHA-256 of the game's script files in the APK. */",
    "public final class Next2DAssetIntegrityManifest {",
    "    public static final String[] LINES = {",
    ...lines.map((line) => `        ${javaString(line)},`),
    "    };",
    "",
    "    private Next2DAssetIntegrityManifest() {}",
    "}",
    ""
].join("\n");

const ANDROID_PROVIDER = [
    `        <!-- ${BEGIN} (generated by @next2d/builder: checks the game files before the app starts) -->`,
    "        <provider",
    `            android:name="${ANDROID_PACKAGE}.Next2DAssetIntegrity"`,
    "            android:authorities=\"${applicationId}.next2d.integrity\"",
    "            android:exported=\"false\"",
    "            android:initOrder=\"2147483647\" />",
    `        <!-- ${END} -->`
].join("\n");

/** AndroidManifest.xml に、照合を行う provider を 1 度だけ足す。 */
export const addAndroidProvider = (manifest: string): string => {
    if (manifest.includes(BEGIN)) {
        return manifest;
    }
    const close = manifest.lastIndexOf("</application>");
    if (close < 0) {
        throw new Error("AndroidManifest.xml has no </application>; the integrity check cannot be registered.");
    }
    const newline = manifest.includes("\r\n") ? "\r\n" : "\n";
    const lineStart = manifest.lastIndexOf("\n", close) + 1;
    return manifest.slice(0, lineStart) + ANDROID_PROVIDER.split("\n").join(newline) + newline + manifest.slice(lineStart);
};

/**
 * Android のプロジェクトに照合を入れる。lines が null のときは照合しない一覧 (空) を書く
 * (開発用の実行では資材が入れ替わるので、古い一覧で起動できなくならないように)。
 */
export const applyAndroidIntegrity = (platformDir: string, lines: string[] | null): void => {
    const manifestFile = path.join(platformDir, "app/src/main/AndroidManifest.xml");
    if (!fs.existsSync(manifestFile)) {
        throw new Error(`AndroidManifest.xml was not found: ${manifestFile}`);
    }
    const sourceDir = path.join(platformDir, "app/src/main/java", ...ANDROID_PACKAGE.split("."));
    fs.mkdirSync(sourceDir, { "recursive": true });
    fs.writeFileSync(path.join(sourceDir, "Next2DAssetIntegrity.java"), ANDROID_CHECK_SOURCE);
    fs.writeFileSync(path.join(sourceDir, "Next2DAssetIntegrityManifest.java"), renderAndroidManifestSource(lines ?? []));
    fs.writeFileSync(path.join(sourceDir, ".gitignore"), "# Generated on every build by @next2d/builder\nNext2DAssetIntegrityManifest.java\n");

    const manifest = fs.readFileSync(manifestFile, "utf8");
    const patched = addAndroidProvider(manifest);
    if (patched !== manifest) {
        fs.writeFileSync(manifestFile, patched);
    }
};

