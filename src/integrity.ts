// ビルドしたゲームのファイルが、配布後に書き換えられていないかを確かめるための一覧を作る。
// 一覧 (ファイルごとの SHA-256) は、各プラットフォームのホストに組み込み、ホストが読み込むたびに照合する。
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

export interface IIntegrityManifest {
    algorithm: "sha256";
    files: Record<string, string>;
}

export const hashData = (data: Buffer | string): string =>
    crypto.createHash("sha256").update(data).digest("hex");

export const hashFile = (file: string): string => hashData(fs.readFileSync(file));

const walk = (directory: string): string[] =>
    fs.readdirSync(directory, { "withFileTypes": true })
        .flatMap((entry) => entry.isDirectory()
            ? walk(path.join(directory, entry.name))
            : entry.isFile() ? [path.join(directory, entry.name)] : []);

/**
 * directory 以下の全ファイルの一覧を作る。キーは directory からの相対パス (区切りは "/")。
 */
export const createIntegrityManifest = (directory: string): IIntegrityManifest => {
    const files: Record<string, string> = {};
    for (const file of walk(directory).sort()) {
        files[path.relative(directory, file).split(path.sep).join("/")] = hashFile(file);
    }
    return { "algorithm": "sha256", files };
};

/**
 * 動作を決めるファイル (スクリプト類) かどうか。ネイティブのホスト (templates/xbox の
 * platform/AssetIntegrity.h) は、この種類のファイルを一覧と照合し、一覧に無いものは読まない。
 * 画像や音声は対象にしない (読み込みのたびに全体のハッシュを取る時間をかけないため)。
 */
export const isCodeFile = (key: string): boolean =>
    [".js", ".mjs", ".html", ".json", ".wasm"].includes(path.posix.extname(key).toLowerCase());

/**
 * ネイティブのホストに渡す一覧の行。1 行 1 ファイルで "<SHA-256><空白 2 つ><キー>" (sha256sum と同じ)。
 * 対象はスクリプト類だけ。
 */
export const createIntegrityLines = (entries: [string, Buffer][]): string[] =>
    entries
        .filter(([key]) => isCodeFile(key))
        .map(([key, data]) => {
            if (/[\r\n]/.test(key)) {
                throw new Error(`A file name with a line break cannot be listed for the integrity check: ${JSON.stringify(key)}`);
            }
            return `${hashData(data)}  ${key}`;
        })
        .sort();

/**
 * 一覧を C++ のヘッダにする (templates/xbox/src/AssetIntegrityManifest.h を置き換える内容)。
 * 1 ファイルを 1 つの文字列リテラルにして、コンパイラの文字列リテラルの長さの上限に当たらないようにする。
 */
export const renderIntegrityHeader = (lines: string[]): string => {
    const literal = (line: string): string =>
        `    "${line.replace(/\\/g, "\\\\").replace(/"/g, "\\\"")}",`;
    return [
        "#pragma once",
        "",
        "// Generated by @next2d/builder. SHA-256 of the game's script files at build time.",
        "// The host refuses to load a listed file whose content differs, and any script that is not listed.",
        "",
        "namespace next2d {",
        "",
        "inline const char* const kAssetIntegrityLines[] = {",
        ...lines.map(literal),
        "    nullptr",
        "};",
        "",
        "} // namespace next2d",
        ""
    ].join("\n");
};
