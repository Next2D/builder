const IOS_CALL = "        Next2DAssetIntegrity.verify() // next2d-integrity:call (generated by @next2d/builder)";

/** AppDelegate.swift に足す照合の処理。内容はビルドによらず同じ。 */
export const IOS_CHECK_SOURCE = `// ${BEGIN} (generated by @next2d/builder; do not edit)
import CryptoKit

/// Checks at launch that the game's script files in the app bundle are the ones that were built.
/// The expected SHA-256 hashes are listed in public/${IOS_MANIFEST_NAME}, written on every build.
/// A changed or added script stops the app. Without the list (a build that skipped the builder) nothing is checked.
enum Next2DAssetIntegrity {
    private static let codeExtensions: Set<String> = ["js", "mjs", "html", "json", "wasm"]

    static func verify() {
        guard let base = Bundle.main.resourceURL?.resolvingSymlinksInPath(),
              let text = try? String(contentsOf: base.appendingPathComponent("public/${IOS_MANIFEST_NAME}"), encoding: .utf8) else {
            return
        }
        var expected: [String: String] = [:]
        for line in text.split(whereSeparator: { $0 == "\\n" || $0 == "\\r" }) where line.count > 66 {
            // "<64 hex digits><two spaces><path relative to the bundle>"
            expected[String(line.dropFirst(66))] = String(line.prefix(64))
        }
        if expected.isEmpty {
            return
        }
        for (key, hash) in expected {
            guard let data = try? Data(contentsOf: base.appendingPathComponent(key)),
                  SHA256.hash(data: data).map({ String(format: "%02x", $0) }).joined() == hash else {
                fatalError("The game files have been modified: \\(key)")
            }
        }
        // A script that was added after the build is not in the list.
        let publicURL = base.appendingPathComponent("public")
        let prefix = base.pathComponents.count
        guard let enumerator = FileManager.default.enumerator(at: publicURL, includingPropertiesForKeys: nil) else {
            return
        }
        for case let url as URL in enumerator where codeExtensions.contains(url.pathExtension.lowercased()) {
            let key = url.resolvingSymlinksInPath().pathComponents.dropFirst(prefix).joined(separator: "/")
            if expected[key] == nil {
                fatalError("The game files have been modified: \\(key)")
            }
        }
    }
}
// ${END}
`;

/** AppDelegate.swift に、照合の処理と、起動時の呼び出しを 1 度だけ足す (処理のほうは常に最新へ置き換える)。 */
export const addIosCheck = (source: string): string => {
    const newline = source.includes("\r\n") ? "\r\n" : "\n";
    const block = IOS_CHECK_SOURCE.split("\n").join(newline);
    const begin = source.indexOf(`// ${BEGIN}`);
    let result = source;
    if (begin >= 0) {
        const endMarker = `// ${END}`;
        const end = source.indexOf(endMarker, begin);
        if (end < 0) {
            throw new Error("AppDelegate.swift has an unterminated next2d-integrity block; remove it and build again.");
        }
        let after = end + endMarker.length;
        if (source.startsWith(newline, after)) {
            after += newline.length;
        }
        result = source.slice(0, begin) + block + source.slice(after);
    } else {
        result = source + (source.endsWith(newline) ? "" : newline) + newline + block;
    }
    if (!result.includes("next2d-integrity:call")) {
        const launch = /didFinishLaunchingWithOptions[^{]*\{[ \t]*\r?\n/.exec(result);
        if (!launch) {
            throw new Error("AppDelegate.swift has no application(_:didFinishLaunchingWithOptions:); the integrity check cannot be called.");
        }
        const at = launch.index + launch[0].length;
        result = result.slice(0, at) + IOS_CALL + newline + result.slice(at);
    }
    return result;
};

/**
 * iOS のプロジェクトに照合を入れる。lines が null のときは一覧を消す (照合しない)。
 * 一覧は public/ に置くので、アプリのバンドルに入り、ゲームのリポジトリには残らない。
 */
export const applyIosIntegrity = (platformDir: string, lines: string[] | null): void => {
    const appDir = path.join(platformDir, "App/App");
    const delegate = path.join(appDir, "AppDelegate.swift");
    if (!fs.existsSync(delegate)) {
        throw new Error(`AppDelegate.swift was not found: ${delegate}`);
    }
    const source = fs.readFileSync(delegate, "utf8");
    const patched = addIosCheck(source);
    if (patched !== source) {
        fs.writeFileSync(delegate, patched);
    }
    const list = path.join(appDir, "public", IOS_MANIFEST_NAME);
    if (lines && lines.length) {
        fs.mkdirSync(path.dirname(list), { "recursive": true });
        fs.writeFileSync(list, `${lines.join("\n")}\n`);
    } else {
        fs.rmSync(list, { "force": true });
    }
};
